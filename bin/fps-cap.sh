#!/usr/bin/env bash
# Live MangoHud frame cap. Usage: fps-cap.sh A [B C...] -> cycle A, B, C... from the current cap. 0 = uncapped.
# Pressed in a MangoHud game, the cap is remembered for that game; pressed anywhere else it sets the default.
# fps-cap.sh focus PID -> apply PID's remembered cap (Hyprland calls this on every focus change).
# fps-cap.sh hud -> show/hide the overlay. Kept in the conf so a cap change doesn't reset it.
# Running games only re-read the conf they loaded at launch, which is MangoHud.conf (per-app confs
# only load at launch), so caps live in a state file and the focused game's cap is written here.
# This script is the source of truth for MangoHud.conf. Games need launch options: mangohud %command%
CONF="$HOME/.config/MangoHud/MangoHud.conf"
CAPS="$HOME/.local/state/fps-cap/caps" # lines: "<game> <cap>", game "default" for everything else

game_of() { # MangoHud game name for PID: exe basename, or wine-<exe> for Proton. Empty if no MangoHud.
	grep -q MangoHud "/proc/$1/maps" 2>/dev/null || return
	local exe w
	exe=$(basename "$(readlink "/proc/$1/exe")")
	if [[ $exe == wine* ]]; then
		w=$(tr '\0' '\n' <"/proc/$1/cmdline" | grep -im1 '\.exe$' | tr '\\' /)
		w=${w##*/}
		[ -n "$w" ] && echo "wine-${w%.*}"
	else
		echo "$exe"
	fi
}
saved() { sed -n "s/^$1 //p" "$CAPS" 2>/dev/null | tail -1; }

cur=$(sed -n 's/^fps_limit=//p' "$CONF" 2>/dev/null)
hidden=$(grep -qx no_display "$CONF" 2>/dev/null || [ ! -f "$CONF" ] && echo 1)

case "$1" in
focus)
	g=$(game_of "$2")
	[ -n "$g" ] || exit 0
	new=$(saved "$g")
	new=${new:-$(saved default)}
	[ -z "$new" ] || [ "$new" = "$cur" ] && exit 0
	;;
hud)
	new=${cur:-225}
	[ -n "$hidden" ] && hidden= || hidden=1
	;;
*)
	g=$(game_of "$(hyprctl activewindow -j | jq -r '.pid // empty')")
	g=${g:-default}
	from=$(saved "$g")
	from=${from:-$(saved default)}
	from=${from:-$cur}
	caps=("$@")
	new=$1
	for i in "${!caps[@]}"; do [ "${caps[i]}" = "$from" ] && new=${caps[i+1]:-$1}; done
	mkdir -p "$(dirname "$CAPS")"
	{ grep -v "^$g " "$CAPS" 2>/dev/null; echo "$g $new"; } >"$CAPS.tmp" && mv "$CAPS.tmp" "$CAPS"
	;;
esac

mkdir -p "$(dirname "$CONF")"
cat >"$CONF" <<CONF
# Generated by ~/bin/fps-cap.sh (Shift+F1..F7 in Hyprland). Edit the script, not this file.
fps_limit=$new
# early = flattest frametimes, late = lowest input latency
fps_limit_method=late
${hidden:+no_display}
control=mangohud
# MangoHud polls these keys itself, so keep them off the Hyprland Shift+F1..F7 cap binds
toggle_hud=Shift_R+Pause
toggle_logging=Shift_L+F10
toggle_fps_limit=Shift_L+F11
reload_cfg=Shift_L+F9
CONF

mangohudctl set reload_config 1 2>/dev/null # "reload-cfg" (in its usage text) fails on 0.8.4
[ "$1" = focus ] || [ "$1" = hud ] && exit
[ "$new" = 0 ] && label="uncapped" || label="$new fps"
omarchy-notification-send -u low "Frame cap: $label" "$g"
