#!/usr/bin/env bash
# Live MangoHud frame cap. Usage: fps-cap.sh A [B C...] -> cycle A, B, C... from the current cap. 0 = uncapped.
# Pressed in a MangoHud game, the cap is remembered for that game (MangoHud's per-app <name>.conf, loaded at
# launch); pressed anywhere else it sets the default in MangoHud.conf.
# fps-cap.sh hud -> show/hide the overlay in every conf. Kept in the confs so a cap change doesn't reset it.
# This script is the source of truth for all the confs and reloads running games over MangoHud's
# control socket. Games need launch options: mangohud %command%
DIR="$HOME/.config/MangoHud"
CONF="$DIR/MangoHud.conf"

# The focused window's MangoHud per-app conf name: exe basename, or wine-<exe without .exe> for Proton
pid=$(hyprctl activewindow -j | jq -r '.pid // empty')
if [ -n "$pid" ] && grep -q MangoHud "/proc/$pid/maps" 2>/dev/null; then
	exe=$(basename "$(readlink "/proc/$pid/exe")")
	if [[ $exe == wine* ]]; then
		w=$(tr '\0' '\n' <"/proc/$pid/cmdline" | grep -im1 '\.exe$' | tr '\\' /)
		w=${w##*/}
		[ -n "$w" ] && CONF="$DIR/wine-${w%.*}.conf"
	else
		CONF="$DIR/$exe.conf"
	fi
fi

[ -f "$CONF" ] || CONF_FROM="$DIR/MangoHud.conf" # new game: start from the default's cap and HUD state
cur=$(sed -n 's/^fps_limit=//p' "${CONF_FROM:-$CONF}" 2>/dev/null)
hidden=$(grep -qx no_display "$DIR/MangoHud.conf" 2>/dev/null || [ ! -f "$DIR/MangoHud.conf" ] && echo 1)
caps=("$@")
new=$1
for i in "${!caps[@]}"; do [ "${caps[i]}" = "$cur" ] && new=${caps[i+1]:-$1}; done

write() { # write FILE CAP
	cat >"$1" <<CONF
# Generated by ~/bin/fps-cap.sh (Shift+F1..F7 in Hyprland). Edit the script, not this file.
fps_limit=$2
# early = flattest frametimes, late = lowest input latency
fps_limit_method=late
${hidden:+no_display}
control=mangohud
# MangoHud polls these keys itself, so keep them off the Hyprland Shift+F1..F7 cap binds
toggle_hud=Shift_R+Pause
toggle_logging=Shift_L+F10
toggle_fps_limit=Shift_L+F11
reload_cfg=Shift_L+F9
CONF
}

mkdir -p "$DIR"
if [ "$1" = hud ]; then
	[ -n "$hidden" ] && hidden= || hidden=1
	for f in "$DIR"/*.conf; do
		grep -q "^# Generated by ~/bin/fps-cap.sh" "$f" 2>/dev/null || continue
		c=$(sed -n 's/^fps_limit=//p' "$f" 2>/dev/null)
		write "$f" "${c:-225}"
	done
	mangohudctl reload-cfg 2>/dev/null
	exit
fi

write "$CONF" "$new"
mangohudctl reload-cfg 2>/dev/null
[ "$new" = 0 ] && label="uncapped" || label="$new fps"
[ "$CONF" = "$DIR/MangoHud.conf" ] && game="default" || game=$(basename "$CONF" .conf)
omarchy-notification-send -u low "Frame cap: $label" "$game"
