#!/usr/bin/env bash
# Live MangoHud frame cap. Usage: fps-cap.sh A [B] -> cap A, or B if A is already set. 0 = uncapped.
# fps-cap.sh hud -> show/hide the overlay. Kept in the conf so a cap change doesn't reset it.
# Writes the whole MangoHud.conf (this script is its source of truth) and reloads running games
# over MangoHud's control socket. Games need launch options: mangohud %command%
CONF="$HOME/.config/MangoHud/MangoHud.conf"
cur=$(sed -n 's/^fps_limit=//p' "$CONF" 2>/dev/null)
hidden=$(grep -qx no_display "$CONF" 2>/dev/null || [ ! -f "$CONF" ] && echo 1)
new=$1
[ -n "$2" ] && [ "$cur" = "$1" ] && new=$2
if [ "$1" = hud ]; then
	new=${cur:-225}
	[ -n "$hidden" ] && hidden= || hidden=1
fi

mkdir -p "$(dirname "$CONF")"
cat >"$CONF" <<EOF
# Generated by ~/bin/fps-cap.sh (Shift+F1..F5 in Hyprland). Edit the script, not this file.
fps_limit=$new
# early = flattest frametimes, late = lowest input latency
fps_limit_method=late
${hidden:+no_display}
control=mangohud
# MangoHud polls these keys itself, so keep them off the Hyprland Shift+F1..F5 cap binds
toggle_hud=Shift_R+Pause
toggle_logging=Shift_L+F10
toggle_fps_limit=Shift_L+F11
reload_cfg=Shift_L+F9
EOF

mangohudctl reload-cfg 2>/dev/null
[ "$1" = hud ] && exit
[ "$new" = 0 ] && label="uncapped" || label="$new fps"
omarchy-notification-send -u low "Frame cap: $label"
